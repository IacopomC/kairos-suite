#!/usr/bin/env python3
r"""Stage A (embodied): dump the robot field-of-view training stream to the
online CLiFF-map CSV schema.

The ATC / HB flow baselines train on the detection stream a
simulated robot sees as it patrols the authored 3DSG: at each keyframe, the
detections within the active-window (field-of-view) radius of the robot pose.
This is generated by `grounded_sim/robot_sim.py` + the per-keyframe FoV filter
in `run_rheos_atc.py` / `run_aion_atc.py`. Because that path depends on
`spark_dsg` (graph loading) and the exact place-node ordering, it must run in
the same Docker image the baselines use (kairos-suite), NOT in the
online-mod venv.

This script REUSES the benchmark's own `robot_sim`, `atc_stream`, and
`hb_stream` unchanged, reproducing the rheos training loop's FoV filter
(graph-box bounds pos +/- 6 m, active radius 5 m, serpentine coverage loop, 10 Hz
keyframes, robot speed 1.5 m/s), and writes, per day, the seen detections in the
online CLiFF-map 6-column schema (time, person_id, x, y, velocity, motion_angle).
It also writes bounds.json so the venv-side scorer uses the identical detection
rectangle for the held-out test days. It does NOT use online-mod's own FoV
simulator.

TBD differs: it is a real robot recording, so there is nothing to simulate. The
field of view follows the logged pose in each scene's poses.csv (`tbd_stream.
TbdPoseTrack`) and the detection rectangle comes from where the robot drove
rather than from a graph box. That path needs no `spark_dsg`, so `--stream-source
tbd` runs in the online-mod venv directly. The radial gate is the same in both
cases, and mirrors the active-voxel test KAIROS applies to every detection in
FlowTemporalModule::processFrame, whose radius is map_window.max_radius_m.

Output is the online CLiFF-map's training input; the online build + scoring runs
separately in the venv (rescore_heading_dist_online_cliff_embodied.py).

Usage:
    # ATC: dump what the simulated robot would have seen over the train days
    python3 extract_fov_stream_online_cliff.py \
        --graph /data/atc/graph/atc_graph.json \
        --days <train npz...> --out-dir <extract-dir> --stream-source atc

    # HB: dates rather than files, and the station's own root
    python3 extract_fov_stream_online_cliff.py --graph <hb_graph.json> \
        --days 2022-09-05 2022-09-06 --out-dir <extract-dir> \
        --stream-source hb --station HB

Stage A of two: writes the field-of-view training stream plus a bounds.json, for
a method that cannot read the suite's own stream objects. Stage B is one of the
rescore_heading_dist_online_cliff_* scripts.
"""
import argparse
import json
import pathlib
import sys
import time

import numpy as np

_HERE = pathlib.Path(__file__).resolve().parent
GS = _HERE.parent / "grounded_sim"
sys.path.insert(0, str(GS))

from robot_sim import (load_nav_graph, build_coverage_loop, RobotSim,  # noqa: E402
                       KEYFRAME_DT_S, ROBOT_SPEED_MPS, ACTIVE_WINDOW_RADIUS_M)


def _open_stream(source, day, xb, yb, hb_root, station, interp_hz, gap_max_s):
    if source == "atc":
        from atc_stream import AtcStream
        return AtcStream(day, x_bounds=xb, y_bounds=yb)
    if source == "tbd":
        from tbd_stream import TbdStream
        return TbdStream(f"{day}/tracks.csv", x_bounds=xb, y_bounds=yb)
    from hb_stream import HBDayStream, hb_day_files
    files = hb_day_files(hb_root, station, day)
    if not files:
        raise SystemExit(f"[extract] no hb files for {day}")
    return HBDayStream(files, x_bounds=xb, y_bounds=yb,
                          interp_hz=interp_hz, gap_max_s=gap_max_s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", default=None,
                    help="authored 3DSG the simulated patrol follows. Required "
                         "for atc/hb; unused for tbd, which has a logged pose.")
    ap.add_argument("--days", nargs="+", required=True,
                    help="train days: ATC npz paths, hb ISO dates, or TBD scene dirs")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--stream-source", default="atc", choices=["atc", "hb", "tbd"])
    ap.add_argument("--hb-root", default="/data/hb-station/Data-2")
    ap.add_argument("--station", choices=["HB", "PB"], default="HB")
    ap.add_argument("--interp-hz", type=float, default=10.0)
    ap.add_argument("--gap-max-s", type=float, default=2.0)
    ap.add_argument("--fov-m", type=float, default=ACTIVE_WINDOW_RADIUS_M)
    ap.add_argument("--robot-speed", type=float, default=ROBOT_SPEED_MPS)
    ap.add_argument("--minutes", type=float, default=0.0,
                    help="sanity slice: cap each day to this many minutes (0 = full day)")
    args = ap.parse_args()
    out = pathlib.Path(args.out_dir); out.mkdir(parents=True, exist_ok=True)

    # ATC / HB have no logged robot, so the field of view follows a simulated
    # patrol over the authored graph. TBD is a real robot recording: its pose is
    # in each scene's poses.csv, so the patrol is replaced by that trajectory and
    # the detection rectangle is derived from where the robot actually drove.
    if args.stream_source == "tbd":
        from tbd_stream import TbdPoseTrack
        pose_tracks = {day: TbdPoseTrack(f"{day}/poses.csv") for day in args.days}
        rx = np.concatenate([p.x for p in pose_tracks.values()])
        ry = np.concatenate([p.y for p in pose_tracks.values()])
        sim = None
        xb = (float(rx.min() - 6), float(rx.max() + 6))
        yb = (float(ry.min() - 6), float(ry.max() + 6))
        print(f"[extract] {len(args.days)} TBD scenes, logged pose "
              f"({len(rx)} samples), bounds x{xb} y{yb}", flush=True)
    else:
        if not args.graph:
            raise SystemExit("[extract] --graph is required for --stream-source "
                             f"{args.stream_source}")
        pose_tracks = None
        pos, node_ids, adj, trav = load_nav_graph(args.graph)
        poly, _ = build_coverage_loop(pos, adj, trav)
        sim = RobotSim(poly, pos, radius=args.fov_m, speed=args.robot_speed)
        xb = (float(pos[:, 0].min() - 6), float(pos[:, 0].max() + 6))
        yb = (float(pos[:, 1].min() - 6), float(pos[:, 1].max() + 6))
        print(f"[extract] {len(pos)} places, coverage loop {sim.total:.0f} m, "
              f"{len(args.days)} days, bounds x{xb} y{yb}", flush=True)
    r2 = args.fov_m ** 2

    (out / "bounds.json").write_text(json.dumps({
        "graph": args.graph, "stream_source": args.stream_source,
        "station": args.station, "x_bounds": xb, "y_bounds": yb,
        "fov_m": args.fov_m,
        "pose_source": "logged" if pose_tracks is not None else "simulated_patrol",
        "robot_speed": None if pose_tracks is not None else args.robot_speed,
        "keyframe_dt_s": KEYFRAME_DT_S, "interp_hz": args.interp_hz,
        "gap_max_s": args.gap_max_s, "minutes": args.minutes,
        "days": [pathlib.Path(d).stem for d in args.days],
    }, indent=1) + "\n")

    manifest = []
    for day in args.days:
        stem = pathlib.Path(day).stem
        s = _open_stream(args.stream_source, day, xb, yb, args.hb_root,
                         args.station, args.interp_hz, args.gap_max_s)
        t0 = s.t_min
        dur = (s.t_max - t0) if args.minutes == 0 else args.minutes * 60.0
        n_kf = int(dur / KEYFRAME_DT_S)
        seen_t, seen_x, seen_y, seen_rho, seen_th, seen_id = [], [], [], [], [], []
        tic = time.time()
        for k in range(n_kf):
            t = t0 + k * KEYFRAME_DT_S
            pose = (pose_tracks[day].pose_at(t) if pose_tracks is not None
                    else sim.pose_at_arclength(args.robot_speed * k * KEYFRAME_DT_S))
            lo = np.searchsorted(s.t, t, "left")
            hi = np.searchsorted(s.t, t + KEYFRAME_DT_S, "left")
            if hi <= lo:
                continue
            dx = s.x[lo:hi]; dy = s.y[lo:hi]
            m = ((dx - pose[0]) ** 2 + (dy - pose[1]) ** 2) <= r2
            if not m.any():
                continue
            idx = np.nonzero(m)[0]
            seen_t.append(s.t[lo:hi][idx]); seen_x.append(dx[idx]); seen_y.append(dy[idx])
            seen_rho.append(s.rho[lo:hi][idx]); seen_th.append(s.theta[lo:hi][idx])
            seen_id.append(s.id[lo:hi][idx])
        if seen_t:
            cols = np.column_stack([
                np.concatenate(seen_t), np.concatenate(seen_id).astype(float),
                np.concatenate(seen_x), np.concatenate(seen_y),
                np.concatenate(seen_rho), np.concatenate(seen_th)])
        else:
            cols = np.empty((0, 6))
        csv_path = out / f"train_{stem}.csv"
        np.savetxt(csv_path, cols, delimiter=",",
                   fmt=["%.6f", "%d", "%.6f", "%.6f", "%.6f", "%.6f"])
        manifest.append(csv_path.name)
        print(f"[extract]   {stem}: {len(cols)} FoV dets -> {csv_path.name} "
              f"({time.time()-tic:.0f}s)", flush=True)

    (out / "train_manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(f"[extract] wrote {len(manifest)} day CSVs + bounds.json to {out}", flush=True)


if __name__ == "__main__":
    main()
